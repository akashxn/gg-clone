/** Countries present in the dataset, alphabetical, with their location counts. */
export const COUNTRIES: { name: string; continent: Continent; count: number }[] = (() => {
  const map = new Map<string, { name: string; continent: Continent; count: number }>();
  for (const loc of LOCATIONS) {
    const found = map.get(loc.country);
    if (found) found.count += 1;
    else map.set(loc.country, { name: loc.country, continent: loc.continent, count: 1 });
  }
  return [...map.values()].sort((a, b) => a.name.localeCompare(b.name));
})();
